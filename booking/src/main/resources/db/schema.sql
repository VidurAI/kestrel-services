-- Kestrel booking schema. Idempotent: safe to run on every start.

create table if not exists carriers (
    id                 bigint generated by default as identity primary key,
    code               varchar(8)    not null unique,
    name               varchar(80)   not null,
    active             boolean       not null default true,
    base_transit_hours integer       not null,
    reliability        numeric(4, 3) not null,
    max_weight_kg      numeric(10, 2) not null
);

create table if not exists shipments (
    id           bigint generated by default as identity primary key,
    reference    varchar(24)    not null unique,
    origin       varchar(5)     not null,
    destination  varchar(5)     not null,
    carrier_id   bigint REFERENCES carriers(id),
    weight_kg    numeric(10, 2) not null,
    status       varchar(16)    not null,
    eta          timestamp with time zone,
    created_at   timestamp with time zone not null,
    updated_at   timestamp with time zone not null
);

create index if not exists idx_shipments_status on shipments (status);
create index if not exists idx_shipments_carrier_status on shipments (carrier_id, status);

create table if not exists shipment_events (
    id          bigint generated by default as identity primary key,
    shipment_id bigint       not null,
    event_type  varchar(32)  not null,
    detail      varchar(255),
    occurred_at timestamp with time zone not null
);

create index if not exists idx_shipment_events_shipment on shipment_events (shipment_id, occurred_at);
